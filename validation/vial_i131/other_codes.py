# Common: the axisymmetric geometry on a 1 mm grid
#
# z slabs of 1 mm from the bottom of the vial (-2.25 cm) to its top (+2.25 cm);
# radii 0.4 (axial profile), 1.0 (cavity/water) and 1.1 cm (glass).
Z0 = -V.VIAL_H / 2
NZ = round(V.VIAL_H / V.VOXEL)                 # 45 slabs of the vial
SLAB_WATER = range(1, 1 + round(V.WAT_H / V.VOXEL))        # slabs 1..32 (0-based)
SLAB_CAVITY_AIR = range(SLAB_WATER.stop, NZ - 1)           # 33..43
PROFILE_R = 0.4


def medium_at(slab, ring):
    """Medium of vial slab `slab` (0..44, from the bottom) and ring
    (0: r < 0.4, 1: 0.4-1.0, 2: 1.0-1.1 cm)."""
    if ring == 2 or slab == 0 or slab == NZ - 1:
        return "glass"
    if slab in SLAB_WATER:
        return "water"
    return "air"


def histogram(lines=None, hist=None):
    """Spectrum as contiguous histogram bins [(E_low, E_high, p)] in MeV.
    A line becomes a 1 eV wide bin, with empty bins between the lines (the way
    EGSnrc writes line spectra such as co60.spectrum)."""
    if hist:
        return [(lo, hi, p) for lo, hi, p in hist]
    half = 0.5e-6
    out = []
    for e_kev, p, _ in sorted(lines, key=lambda l: l[0]):
        e = e_kev * 1e-3
        lo = e - half
        if out and lo > out[-1][1]:
            out.append((out[-1][1], lo, 0.0))
        elif out:
            lo = out[-1][1]
        out.append((lo, e + half, p))
    return out


