# EGSnrc: DOSRZnrc
EGS_MEDIA = {"water": "VialWater", "air": "VialAir", "glass": "VialGlass"}


def egsnrc_spectrum(nuclide, origin, lines=None, hist=None):
    bins = histogram(lines, hist)
    head = f"{nuclide} {'beta-minus spectrum' if hist else 'photon lines'} (Guaraci benchmark)"[:80]
    rows = [f"{hi:.9f}, {p:.6e}" for _, hi, p in bins]
    return f"{head}\n{len(bins)}, {bins[0][0]:.9f}, 0\n" + "\n".join(rows) + "\n"


